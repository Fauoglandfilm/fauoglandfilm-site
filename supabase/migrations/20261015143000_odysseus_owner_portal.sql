-- Private Odysseus owner portal. All access is server-side through the service
-- role after owner or device authentication; browser clients receive no table
-- privileges and RLS remains enabled as a second boundary.

create table if not exists public.odysseus_devices (
  id text primary key,
  name text not null,
  agent_version text not null default '',
  last_seen_at timestamptz,
  status_snapshot jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.odysseus_commands (
  id uuid primary key,
  device_id text not null references public.odysseus_devices(id) on delete cascade,
  created_by uuid references auth.users(id) on delete set null,
  action text not null check (action in (
    'pause_system','resume_system','refresh_status','run_crm_sync',
    'run_sales_maintenance','stop_delivery','set_daily_send_limit'
  )),
  payload jsonb not null default '{}'::jsonb,
  status text not null default 'queued' check (status in ('queued','running','completed','failed','cancelled')),
  idempotency_key text not null unique,
  result jsonb,
  error_code text,
  created_at timestamptz not null default now(),
  started_at timestamptz,
  completed_at timestamptz
);

create index if not exists odysseus_commands_queue_idx
  on public.odysseus_commands (device_id, status, created_at);

create table if not exists public.odysseus_audit_logs (
  id bigint generated by default as identity primary key,
  actor_user_id uuid references auth.users(id) on delete set null,
  event_type text not null,
  command_id uuid references public.odysseus_commands(id) on delete set null,
  detail jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.odysseus_devices enable row level security;
alter table public.odysseus_commands enable row level security;
alter table public.odysseus_audit_logs enable row level security;

revoke all on public.odysseus_devices from anon, authenticated;
revoke all on public.odysseus_commands from anon, authenticated;
revoke all on public.odysseus_audit_logs from anon, authenticated;
